router.post("/", async (req, res) => {
  try {
    const now = Date.now();
    if (now - lastSubmitTime < SERVER_RATE_LIMIT_MS) {
      return res.status(429).json({ error: "Too many submissions, slow down" });
    }
    lastSubmitTime = now;

    const body = req.body;
    if (!body.title || typeof body.title !== "string" || body.title.trim().length < 3) {
      return res.status(400).json({ error: "Title must be at least 3 characters" });
    }
    if (!body.description || typeof body.description !== "string" || body.description.trim().length < 5) {
      return res.status(400).json({ error: "Description must be at least 5 characters" });
    }
    if (body.category && !VALID_CATEGORIES.has(body.category)) {
      return res.status(400).json({ error: "Invalid category" });
    }
    if (body.priority && !VALID_PRIORITIES.has(body.priority)) {
      return res.status(400).json({ error: "Invalid priority" });
    }

    body.title = body.title.trim().slice(0, 200);
    body.description = body.description.trim().slice(0, 3000);
    if (body.codeSnippet) body.codeSnippet = String(body.codeSnippet).slice(0, 10000);
    if (body.codeLanguage) body.codeLanguage = String(body.codeLanguage).slice(0, 30);
    if (body.estimatedImpact) body.estimatedImpact = String(body.estimatedImpact).slice(0, 500);
    if (body.source) body.source = String(body.source).slice(0, 100);
    if (body.targetFiles && Array.isArray(body.targetFiles)) {
      body.targetFiles = body.targetFiles.slice(0, 10).map((f: any) => String(f).slice(0, 200));
    }
    if (body.painPointsAddressed && Array.isArray(body.painPointsAddressed)) {
      body.painPointsAddressed = body.painPointsAddressed.slice(0, 10).map((p: any) => String(p).slice(0, 200));
    }
    if (body.tags && Array.isArray(body.tags)) {
      body.tags = body.tags.slice(0, 10).map((t: any) => String(t).slice(0, 50));
    }

    if (isDuplicate(body.title)) {
      return res.status(409).json({ error: "Duplicate recommendation recently submitted" });
    }

    const existing = await storage.getAllRecommendations();
    if (existing.length >= MAX_STORED_ITEMS) {
      return res.status(507).json({ error: "Recommendation storage limit reached" });
    }

    const parsed = insertAgentRecommendationSchema.parse(body);
    const item = await storage.createRecommendation(parsed);

    syncToFiles([...existing, item]).catch(() => {});

    res.json(item);
  } catch (err: any) {
    res.status(400).json({ error: err.message });
  }
});

router.patch("/:id", async (req, res) => {
  try {
    const id = parseInt(req.params.id);
    if (isNaN(id)) return res.status(400).json({ error: "Invalid ID" });

    const updates: Record<string, any> = {};
    if (req.body.status && VALID_STATUSES.has(req.body.status)) updates.status = req.body.status;
    if (req.body.priority && VALID_PRIORITIES.has(req.body.priority)) updates.priority = req.body.priority;

    if (Object.keys(updates).length === 0) {
      return res.status(400).json({ error: "No valid updates provided" });
    }

    const updated = await storage.updateRecommendation(id, updates);
    if (!updated) return res.status(404).json({ error: "Not found" });
    res.json(updated);
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

