import { Router } from "express";
import { storage } from "../storage";
import { insertAgentRecommendationSchema } from "@shared/schema";
import * as fs from "fs";
import * as path from "path";

const router = Router();

const VALID_CATEGORIES = new Set(["code_snippet", "file_edit", "systemic", "integration", "new_tool"]);
const VALID_PRIORITIES = new Set(["low", "medium", "high", "critical"]);
const VALID_STATUSES = new Set(["proposed", "accepted", "implemented", "rejected"]);

const recentSubmissions = new Map<string, number>();
const SERVER_RATE_LIMIT_MS = 2000;
const MAX_STORED_ITEMS = 300;

function isDuplicate(title: string): boolean {
  const key = title.trim().toLowerCase().slice(0, 60);
  const now = Date.now();
  const last = recentSubmissions.get(key);
  if (last && now - last < 60000) return true;
  recentSubmissions.set(key, now);
  if (recentSubmissions.size > 200) {
    const entries = Array.from(recentSubmissions.entries())
      .sort((a, b) => a[1] - b[1])
      .slice(0, 100);
    entries.forEach(([k]) => recentSubmissions.delete(k));
  }
  return false;
}

let lastSubmitTime = 0;

const CATEGORY_LABELS: Record<string, string> = {
  code_snippet: "Code Snippet",
  file_edit: "File Edit",
  systemic: "Systemic Improvement",
  integration: "Integration",
  new_tool: "New Tool",
};

const PRIORITY_EMOJI: Record<string, string> = {
  critical: "🔴",
  high: "🟠",
  medium: "🟡",
  low: "⚪",
};

function recToPrompt(rec: any): string {
  const lines = [
    `## Task: ${rec.title}`,
    `**Category**: ${CATEGORY_LABELS[rec.category] || rec.category}`,
    `**Priority**: ${rec.priority}`,
    ``,
    `### Description`,
    rec.description,
    ``,
  ];
  if (rec.targetFiles && rec.targetFiles.length > 0) {
    lines.push(`### Target Files`);
    rec.targetFiles.forEach((f: string) => lines.push(`- \`${f}\``));
    lines.push(``);
  }
  if (rec.painPointsAddressed && rec.painPointsAddressed.length > 0) {
    lines.push(`### Pain Points This Solves`);
    rec.painPointsAddressed.forEach((p: string) => lines.push(`- ${p}`));
    lines.push(``);
  }
  if (rec.codeSnippet) {
    lines.push(`### Starter Code`);
    lines.push(`\`\`\`${rec.codeLanguage || 'typescript'}`);
    lines.push(rec.codeSnippet);
    lines.push(`\`\`\``);
    lines.push(``);
  }
  if (rec.estimatedImpact) {
    lines.push(`### Expected Impact`);
    lines.push(rec.estimatedImpact);
    lines.push(``);
  }
  return lines.join('\n');
}

function recToAgentPrompt(rec: any): string {
  const parts = [
    `Implement the following change in this codebase:`,
    ``,
    `TITLE: ${rec.title}`,
    `CATEGORY: ${CATEGORY_LABELS[rec.category] || rec.category}`,
    `PRIORITY: ${rec.priority}`,
    ``,
    `WHAT TO DO:`,
    rec.description,
  ];
  if (rec.targetFiles && rec.targetFiles.length > 0) {
    parts.push(``, `FILES TO MODIFY:`);
    rec.targetFiles.forEach((f: string) => parts.push(`  - ${f}`));
  }
  if (rec.painPointsAddressed && rec.painPointsAddressed.length > 0) {
    parts.push(``, `PAIN POINTS THIS FIXES:`);
    rec.painPointsAddressed.forEach((p: string) => parts.push(`  - ${p}`));
  }
  if (rec.codeSnippet) {
    parts.push(``, `STARTER CODE (use as reference, adapt to codebase patterns):`);
    parts.push(`\`\`\`${rec.codeLanguage || 'typescript'}`);
    parts.push(rec.codeSnippet);
    parts.push(`\`\`\``);
  }
  if (rec.estimatedImpact) {
    parts.push(``, `EXPECTED IMPACT: ${rec.estimatedImpact}`);
  }
  parts.push(``, `INSTRUCTIONS: Read the target files first, understand existing patterns, then implement this change following project conventions (React + TypeScript + Tailwind + Drizzle ORM). Test your changes.`);
  return parts.join('\n');
}

function generateMarkdown(recs: any[]): string {
  const now = new Date().toISOString().split('T')[0];
  const lines = [
    `# Agent Recommendations`,
    ``,
    `> Auto-generated by NEXUS agents. Last synced: ${now}`,
    `> These are actionable platform improvements with starter code.`,
    `> Feed individual items to any coding agent (Replit, Cursor, Copilot, Claude, etc.) to implement them.`,
    ``,
    `| # | Category | Priority | Title | Pain Points | Status |`,
    `|---|----------|----------|-------|-------------|--------|`,
  ];

  recs.forEach((rec, i) => {
    const pp = (rec.painPointsAddressed || []).length;
    lines.push(`| ${i + 1} | ${CATEGORY_LABELS[rec.category] || rec.category} | ${PRIORITY_EMOJI[rec.priority] || ''} ${rec.priority} | ${rec.title} | ${pp} | ${rec.status} |`);
  });

  lines.push(``, `---`, ``);

  const grouped: Record<string, any[]> = {};
  recs.forEach(rec => {
    const cat = rec.category;
    if (!grouped[cat]) grouped[cat] = [];
    grouped[cat].push(rec);
  });

  for (const [cat, items] of Object.entries(grouped)) {
    lines.push(`## ${CATEGORY_LABELS[cat] || cat}s`, ``);
    items.forEach(rec => {
      lines.push(recToPrompt(rec));
      lines.push(`---`, ``);
    });
  }

  lines.push(``, `## How to Use These Recommendations`, ``);
  lines.push(`### With any AI coding agent`);
  lines.push(`Copy a single recommendation section above and paste it as a prompt to your coding agent.`);
  lines.push(``);
  lines.push(`### Via API`);
  lines.push(`\`\`\`bash`);
  lines.push(`# Fetch all recommendations as JSON`);
  lines.push(`curl -s https://YOUR_APP_URL/api/recommendations/export?format=json`);
  lines.push(``);
  lines.push(`# Fetch a single recommendation as an agent-ready prompt`);
  lines.push(`curl -s https://YOUR_APP_URL/api/recommendations/export/1?format=prompt`);
  lines.push(`\`\`\``);
  lines.push(``);
  lines.push(`### Programmatic ingestion`);
  lines.push(`\`\`\`bash`);
  lines.push(`# Pipe a recommendation directly into another tool`);
  lines.push(`curl -s https://YOUR_APP_URL/api/recommendations/export/1?format=prompt | pbcopy`);
  lines.push(`\`\`\``);

  return lines.join('\n');
}

async function syncToFiles(recs: any[]) {
  try {
    const githubDir = path.join(process.cwd(), '.github');
    if (!fs.existsSync(githubDir)) fs.mkdirSync(githubDir, { recursive: true });

    const md = generateMarkdown(recs);
    fs.writeFileSync(path.join(githubDir, 'RECOMMENDATIONS.md'), md, 'utf-8');

    const jsonExport = recs.map(rec => ({
      id: rec.id,
      category: rec.category,
      priority: rec.priority,
      status: rec.status,
      title: rec.title,
      description: rec.description,
      targetFiles: rec.targetFiles || [],
      codeSnippet: rec.codeSnippet || null,
      codeLanguage: rec.codeLanguage || 'typescript',
      painPointsAddressed: rec.painPointsAddressed || [],
      estimatedImpact: rec.estimatedImpact || null,
      source: rec.source,
      votes: rec.votes,
      createdAt: rec.createdAt,
    }));
    fs.writeFileSync(path.join(githubDir, 'recommendations.json'), JSON.stringify(jsonExport, null, 2), 'utf-8');
  } catch (err) {
    console.error('Failed to sync recommendations to files:', err);
  }
}

