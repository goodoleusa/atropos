router.get("/stats", async (_req, res) => {
  try {
    const items = await storage.getAllRecommendations();
    const stats = {
      total: items.length,
      byCategory: {} as Record<string, number>,
      byStatus: { proposed: 0, accepted: 0, implemented: 0, rejected: 0 } as Record<string, number>,
      byPriority: { critical: 0, high: 0, medium: 0, low: 0 } as Record<string, number>,
      topVoted: items.sort((a, b) => b.votes - a.votes).slice(0, 5),
      painPointsCovered: [] as string[],
    };
    const painSet = new Set<string>();
    items.forEach(item => {
      stats.byCategory[item.category] = (stats.byCategory[item.category] || 0) + 1;
      stats.byStatus[item.status] = (stats.byStatus[item.status] || 0) + 1;
      stats.byPriority[item.priority] = (stats.byPriority[item.priority] || 0) + 1;
      if (item.painPointsAddressed) {
        item.painPointsAddressed.forEach((p: string) => painSet.add(p));
      }
    });
    stats.painPointsCovered = Array.from(painSet);
    res.json(stats);
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

router.get("/export", async (req, res) => {
  try {
    const items = await storage.getAllRecommendations();
    const format = (req.query.format as string) || 'json';
    const category = req.query.category as string;
    const status = req.query.status as string;

    let filtered = items;
    if (category && VALID_CATEGORIES.has(category)) {
      filtered = filtered.filter(i => i.category === category);
    }
    if (status && VALID_STATUSES.has(status)) {
      filtered = filtered.filter(i => i.status === status);
    }

    if (format === 'markdown' || format === 'md') {
      res.setHeader('Content-Type', 'text/markdown');
      res.send(generateMarkdown(filtered));
    } else if (format === 'prompt') {
      res.setHeader('Content-Type', 'text/plain');
      const prompts = filtered.map(r => recToAgentPrompt(r));
      res.send(prompts.join('\n\n' + '='.repeat(80) + '\n\n'));
    } else {
      res.json({
        exported: new Date().toISOString(),
        count: filtered.length,
        recommendations: filtered.map(rec => ({
          id: rec.id,
          category: rec.category,
          priority: rec.priority,
          status: rec.status,
          title: rec.title,
          description: rec.description,
          targetFiles: rec.targetFiles || [],
          codeSnippet: rec.codeSnippet || null,
          codeLanguage: rec.codeLanguage || 'typescript',
          painPointsAddressed: rec.painPointsAddressed || [],
          estimatedImpact: rec.estimatedImpact || null,
          source: rec.source,
          votes: rec.votes,
        })),
      });
    }
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

router.get("/export/:id", async (req, res) => {
  try {
    const id = parseInt(req.params.id);
    if (isNaN(id)) return res.status(400).json({ error: "Invalid ID" });
    const rec = await storage.getRecommendationById(id);
    if (!rec) return res.status(404).json({ error: "Not found" });

    const format = (req.query.format as string) || 'json';

    if (format === 'prompt') {
      res.setHeader('Content-Type', 'text/plain');
      res.send(recToAgentPrompt(rec));
    } else if (format === 'markdown' || format === 'md') {
      res.setHeader('Content-Type', 'text/markdown');
      res.send(recToPrompt(rec));
    } else {
      res.json(rec);
    }
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

